/// 人名・地名で頻出する異体字 → 代表字。旧字体テーブルと重複しないものだけ。
///
/// 斎/斉、島/嶋 のように「別の姓として区別される」ものは意見が分かれるが、
/// 名寄せ・検索では同一視した方が取りこぼしが減るため、ここでは統一する。
/// 区別が必要な場合はこのフラグを切る。
